export const GLYPH_W = 5
export const GLYPH_H = 7
export const GLYPH_ADV = 6

export const FONT_CHARS = Object.keys(G)

export function glyphRows(ch: string): string[] {
  return (G[ch.toUpperCase()] ?? G['?']).split('|')
}

export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * GLYPH_ADV - 1) * scale : 0
}
